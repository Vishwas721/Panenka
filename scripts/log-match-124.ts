async function main() {
  console.log("Checking/verifying players in Panenka for Match 124...");

  const playerIds: { [name: string]: string } = {};

  for (const p of matchPlayers) {
    const existing = await prisma.player.findFirst({
      where: {
        fullName: { equals: p.fullName, mode: "insensitive" },
      },
    });

    if (existing) {
      console.log(`Player found: ${existing.fullName} (${existing.id})`);
      playerIds[p.fullName] = existing.id;
    } else {
      const created = await createPlayer({
        fullName: p.fullName,
        displayName: p.displayName,
        position: p.position,
        team: p.team,
        nationality: p.nationality,
      });
      console.log(`Created new player: ${created.fullName} (${created.id})`);
      playerIds[p.fullName] = created.id;
    }
  }

  console.log("\nLogging Match 124 with 14 player performances...");

  const performances = matchPlayers.map((p) => ({
    playerId: playerIds[p.fullName]!,
    appearanceStatus: p.status,
    minutesPlayed: p.minutesPlayed,
    goals: p.goals,
    assists: p.assists,
    rating: p.matchRating,
    isMotm: p.isMotm,
    notes: p.notes,
  }));

  const match = await createMatch({
    date: new Date(),
    opponent: "Division Rival",
    venue: "HOME",
    scoreHome: 2,
    scoreAway: 3,
    status: "COMPLETED",
    notes:
      "eFootball Match 124 logged from player ratings screenshots (2-3 Home Loss, Cole Palmer 1G, Soufiane Rahimi 1G off bench, Samuel Mbangula 1A on debut; Opponent MOTM; Subs: Soufiane Rahimi, Amad Diallo, Riccardo Sottil on at 70' for Cole Palmer, Samuel Mbangula, Mason Mount; 2 Debuts: Samuel Mbangula, Calvin Bassey)",
    performances,
  });

  console.log(`\nMatch 124 successfully created! ID: ${match.id}`);
  console.log(
    `Score: Panenka ${match.scoreHome} - ${match.scoreAway} Opponent (HOME LOSS)`
  );
  console.log(`Appearances recorded: ${match.performances.length}`);
}

main()
  .catch((e) => {
    console.error("Error logging match 124:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
