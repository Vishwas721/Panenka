async function main() {
  console.log("Checking/verifying players in Panenka for Match 136...");

  const playerIds: { [name: string]: string } = {};

  for (const p of matchPlayers) {
    const existing = await prisma.player.findFirst({
      where: {
        fullName: { equals: p.fullName, mode: "insensitive" },
      },
    });

    if (existing) {
      console.log(`Player found: ${existing.fullName} (${existing.id})`);
      playerIds[p.fullName] = existing.id;
    } else {
      const created = await createPlayer({
        fullName: p.fullName,
        displayName: p.displayName,
        position: p.position,
        team: p.team,
        nationality: p.nationality,
      });
      console.log(`Created new player: ${created.fullName} (${created.id})`);
      playerIds[p.fullName] = created.id;
    }
  }

  console.log("\nLogging Match 136 with 14 player performances...");

  const performances = matchPlayers.map((p) => ({
    playerId: playerIds[p.fullName]!,
    appearanceStatus: p.status,
    minutesPlayed: p.minutesPlayed,
    goals: p.goals,
    assists: p.assists,
    rating: p.matchRating,
    isMotm: p.isMotm,
    notes: p.notes,
  }));

  const match = await createMatch({
    date: new Date(),
    opponent: "Division Rival",
    venue: "HOME",
    scoreHome: 3,
    scoreAway: 4,
    status: "COMPLETED",
    notes:
      "eFootball Match 136 logged from player ratings screenshots (3-4 Home Loss, Cole Palmer 1G, Neymar Jr 1G, Jhon Jhon 1G off bench, Weston McKennie 1A, Soufiane Rahimi 1A; Opponent MOTM; Subs: Jhon Jhon, Amad Diallo, Magnus Mattsson on at 70' for Cole Palmer, Olivier Kemen, Mason Mount; Debut: Lutsharel Geertruida)",
    performances,
  });

  console.log(`\nMatch 136 successfully created! ID: ${match.id}`);
  console.log(
    `Score: Panenka ${match.scoreHome} - ${match.scoreAway} Opponent (HOME LOSS)`
  );
  console.log(`Appearances recorded: ${match.performances.length}`);
}

main()
  .catch((e) => {
    console.error("Error logging match 136:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
