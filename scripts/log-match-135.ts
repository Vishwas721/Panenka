async function main() {
  console.log("Checking/verifying players in Panenka for Match 135...");

  const playerIds: { [name: string]: string } = {};

  for (const p of matchPlayers) {
    const existing = await prisma.player.findFirst({
      where: {
        fullName: { equals: p.fullName, mode: "insensitive" },
      },
    });

    if (existing) {
      console.log(`Player found: ${existing.fullName} (${existing.id})`);
      playerIds[p.fullName] = existing.id;
    } else {
      const created = await createPlayer({
        fullName: p.fullName,
        displayName: p.displayName,
        position: p.position,
        team: p.team,
        nationality: p.nationality,
      });
      console.log(`Created new player: ${created.fullName} (${created.id})`);
      playerIds[p.fullName] = created.id;
    }
  }

  console.log("\nLogging Match 135 with 14 player performances...");

  const performances = matchPlayers.map((p) => ({
    playerId: playerIds[p.fullName]!,
    appearanceStatus: p.status,
    minutesPlayed: p.minutesPlayed,
    goals: p.goals,
    assists: p.assists,
    rating: p.matchRating,
    isMotm: p.isMotm,
    notes: p.notes,
  }));

  const match = await createMatch({
    date: new Date(),
    opponent: "Division Rival",
    venue: "HOME",
    scoreHome: 2,
    scoreAway: 5,
    status: "COMPLETED",
    notes:
      "eFootball Match 135 logged from player ratings screenshots (2-5 Home Loss, Soufiane Rahimi 2G, Joey Veerman 1A, Riccardo Sottil 1A; Opponent MOTM; Subs: Neymar Jr, Amad Diallo, Jhon Jhon on at 70' for Riccardo Sottil, Cole Palmer, Mason Mount; 2 Debuts: Yann Sommer, Myles Lewis-Skelly)",
    performances,
  });

  console.log(`\nMatch 135 successfully created! ID: ${match.id}`);
  console.log(
    `Score: Panenka ${match.scoreHome} - ${match.scoreAway} Opponent (HOME LOSS)`
  );
  console.log(`Appearances recorded: ${match.performances.length}`);
}

main()
  .catch((e) => {
    console.error("Error logging match 135:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
